import fs from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const projectRoot = path.resolve(import.meta.dirname, '..')
const sourcePath = path.join(projectRoot, 'node_modules', 'katex', 'dist', 'katex.css')
const outputPath = path.join(projectRoot, 'src', 'renderer', 'src', 'assets', 'katex-woff2.css')
const checkOnly = process.argv.includes('--check')

function toWoff2Only(source) {
  let fontFaces = 0
  const transformed = source.replace(/@font-face\s*\{[\s\S]*?\n\}/g, block => {
    fontFaces += 1
    return block.replace(
      /src:\s*url\(fonts\/([^)]+\.woff2)\)\s*format\("woff2"\)[^;]*;/,
      'src: url(../../../../node_modules/katex/dist/fonts/$1?no-inline) format("woff2");'
    )
  })
  if (fontFaces !== 20) throw new Error(`预期 20 个 KaTeX font-face，实际 ${fontFaces}`)
  if (/\.(?:ttf|woff)(?:\)|["'])/.test(transformed)) throw new Error('生成 CSS 仍包含 TTF/WOFF 引用')
  return `/* Generated by scripts/generate-katex-woff2-css.mjs. Do not edit manually. */\n${transformed}`
}

async function main() {
  const generated = toWoff2Only(await fs.readFile(sourcePath, 'utf8'))
  if (checkOnly) {
    const existing = await fs.readFile(outputPath, 'utf8')
    if (existing !== generated) throw new Error('katex-woff2.css 已过期，请运行 npm run generate:katex-css')
    console.log('KaTeX WOFF2 CSS is up to date')
    return
  }
  await fs.mkdir(path.dirname(outputPath), { recursive: true })
  await fs.writeFile(outputPath, generated)
  console.log(`Generated ${path.relative(projectRoot, outputPath)}`)
}

main().catch(error => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
