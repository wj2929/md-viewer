import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Page, ElectronApplication } from '@playwright/test'
import { test, expect, openFolderViaIPC } from './fixtures/electron'

async function prepareSplit(page: Page, app: ElectronApplication, directory: string): Promise<void> {
  writeFileSync(join(directory, 'test1.md'), '# Left\n\nneedle left\n\nneedle left again\n\nNEEDLE uppercase\n')
  writeFileSync(join(directory, 'code.md'), '# Right\n\nneedle right\n\nneedle right again\n')
  await openFolderViaIPC(app, directory)
  await page.locator('.file-tree-row.file', { hasText: 'test1.md' }).click()
  await expect(page.locator('.markdown-body h1')).toHaveText('Left')
  await page.keyboard.press('Control+\\')
  await expect(page.locator('.split-leaf-panel')).toHaveCount(2)
}

test('分屏搜索只响应活动文档，切换面板不串焦点、计数或导航', async ({ page, electronApp, testDir }, testInfo) => {
  await page.setViewportSize({ width: 1100, height: 720 })
  await prepareSplit(page, electronApp, testDir)
  const left = page.locator('.split-leaf-panel').first()
  const right = page.locator('.split-leaf-panel').last()
  await left.locator('.markdown-body').click()
  await page.keyboard.press('Meta+Shift+f')
  await expect(page.locator('.in-page-search-box')).toHaveCount(1)
  const input = left.getByRole('textbox', { name: '搜索词', exact: true })
  await expect(input).toBeFocused()
  await input.fill('needle')
  await expect(left.locator('.in-page-search-count')).toHaveText('1 / 3')
  await input.press('Enter')
  await expect(left.locator('.in-page-search-count')).toHaveText('2 / 3')
  await input.press('Shift+Enter')
  await expect(left.locator('.in-page-search-count')).toHaveText('1 / 3')
  await expect(right.locator('mark.search-highlight')).toHaveCount(0)
  const bounds = await left.boundingBox()
  const searchBounds = await left.locator('.in-page-search-box').boundingBox()
  expect(searchBounds!.x).toBeGreaterThanOrEqual(bounds!.x)
  expect(searchBounds!.x + searchBounds!.width).toBeLessThanOrEqual(bounds!.x + bounds!.width + 1)
  await page.screenshot({ path: testInfo.outputPath('left-search-narrow.png') })
  await right.locator('.markdown-body').click()
  await expect(left.locator('.in-page-search-box')).toHaveCount(0)
  await page.keyboard.press('Meta+Shift+f')
  const rightInput = right.getByRole('textbox', { name: '搜索词', exact: true })
  await expect(rightInput).toBeFocused()
  await rightInput.fill('needle')
  await expect(right.locator('.in-page-search-count')).toHaveText('1 / 2')
  await rightInput.press('Enter')
  await expect(right.locator('.in-page-search-count')).toHaveText('2 / 2')
  await expect(left.locator('.search-highlight-current')).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath('right-search-narrow.png') })
  await left.locator('.markdown-body').click()
  await expect(left.getByRole('textbox', { name: '搜索词', exact: true })).toHaveValue('needle')
  await expect(left.locator('.in-page-search-count')).toHaveText('1 / 3')
  await left.getByRole('button', { name: '切换大小写敏感' }).click()
  await expect(left.locator('.in-page-search-count')).toHaveText('1 / 2')
})

test('右键搜索绑定右键所在面板，关闭搜索不会删除另一个面板的标记', async ({ page, electronApp, testDir }) => {
  await prepareSplit(page, electronApp, testDir)
  await electronApp.evaluate(({ Menu, BrowserWindow }) => {
    ;(Menu.prototype as unknown as { popup: () => void }).popup = function (this: Electron.Menu) {
      const item = this.items.find(item => item.label.includes('页面内搜索'))
      item?.click(item, BrowserWindow.getAllWindows()[0], {} as Electron.KeyboardEvent)
    }
  })
  const right = page.locator('.split-leaf-panel').last()
  await right.locator('.markdown-body h1').click({ button: 'right' })
  await expect(right).toHaveClass(/active/)
  await expect(page.locator('.in-page-search-box')).toHaveCount(1)
  const input = right.getByRole('textbox', { name: '搜索词', exact: true })
  await expect(input).toBeFocused()
  await input.fill('needle')
  await expect(right.locator('.in-page-search-count')).toHaveText('1 / 2')
  await input.press('Escape')
  await expect(page.locator('.in-page-search-box')).toHaveCount(0)
  await expect(page.locator('mark.search-highlight')).toHaveCount(0)
})

test('分屏关闭其他面板后仍可在单文档重新搜索，正文更新后重算结果', async ({ page, electronApp, testDir }) => {
  await prepareSplit(page, electronApp, testDir)
  const left = page.locator('.split-leaf-panel').first()
  await left.locator('.markdown-body').click()
  await page.keyboard.press('Meta+Shift+f')
  await left.getByRole('textbox', { name: '搜索词', exact: true }).fill('needle')
  await expect(left.locator('.in-page-search-count')).toHaveText('1 / 3')
  writeFileSync(join(testDir, 'test1.md'), '# Left\n\nneedle revised\n')
  await expect(left.locator('.in-page-search-count')).toHaveText('1 / 1')
  await left.getByRole('textbox', { name: '搜索词', exact: true }).press('Escape')
  await expect(page.locator('.in-page-search-box')).toHaveCount(0)
  await page.locator('.split-leaf-panel').last().getByRole('button', { name: '关闭面板' }).click()
  await expect(page.locator('.split-leaf-panel')).toHaveCount(1)
  await expect(page.locator('.split-leaf-panel .markdown-body h1')).toHaveText('Left')
  await page.keyboard.press('Meta+Shift+f')
  await expect(page.locator('.in-page-search-box')).toHaveCount(1)
  await page.locator('.in-page-search-input').fill('needle')
  await expect(page.locator('.in-page-search-count')).toHaveText('1 / 1')
})

test('分屏对照编辑的预览搜索只响应活动面板', async ({ page, electronApp, testDir }) => {
  await prepareSplit(page, electronApp, testDir)
  await electronApp.evaluate(({ Menu, BrowserWindow }) => {
    ;(Menu.prototype as unknown as { popup: () => void }).popup = function (this: Electron.Menu) {
      const item = this.items.find(item => item.label.includes('快速编辑'))
      item?.click(item, BrowserWindow.getAllWindows()[0], {} as Electron.KeyboardEvent)
    }
  })
  const left = page.locator('.split-leaf-panel').first()
  const right = page.locator('.split-leaf-panel').last()
  await left.locator('.markdown-body h1').click({ button: 'right' })
  await expect(left.locator('.markdown-edit-workbench')).toBeVisible()
  await left.locator('.markdown-body h1').click()
  await page.keyboard.press('Meta+Shift+f')
  const input = left.locator('.in-page-search-input')
  await expect(input).toBeFocused()
  await input.fill('needle')
  await expect(left.locator('.in-page-search-count')).toHaveText('1 / 3')
  await expect(right.locator('.in-page-search-box')).toHaveCount(0)
  await right.locator('.markdown-body h1').click()
  await page.keyboard.press('Meta+Shift+f')
  await expect(right.locator('.in-page-search-input')).toBeFocused()
  await expect(left.locator('.in-page-search-box')).toHaveCount(0)
})

test('大文档右键编辑保留默认对照、行定位和草稿保存', async ({ page, electronApp, testDir }, testInfo) => {
  const filePath = join(testDir, 'large-edit.md')
  const content = '# Large Edit\n\n' + Array.from({ length: 2400 }, (_, index) =>
    `- Entry ${index}: local performance fixture with an editable list.\n\n  Details ${index}: source mapping and preview editing must remain available.\n`,
  ).join('\n')
  writeFileSync(filePath, content)
  await openFolderViaIPC(electronApp, testDir)
  await page.locator('.file-tree-row.file', { hasText: 'large-edit.md' }).click()
  await expect(page.locator('.markdown-body h1')).toHaveText('Large Edit')
  await electronApp.evaluate(({ Menu, BrowserWindow }) => {
    ;(Menu.prototype as unknown as { popup: () => void }).popup = function (this: Electron.Menu) {
      const item = this.items.find(item => item.label.includes('快速编辑'))
      item?.click(item, BrowserWindow.getAllWindows()[0], {} as Electron.KeyboardEvent)
    }
  })
  await page.locator('.markdown-body h1').click({ button: 'right' })
  const workbench = page.getByLabel('large-edit.md 编辑工作区')
  await expect(workbench.getByRole('tab', { name: '对照预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  const editor = workbench.getByRole('textbox', { name: 'Markdown 源码编辑区' })
  await expect(editor).toBeVisible()
  await expect(workbench.locator('.markdown-body h1')).toHaveAttribute('data-source-line', '1')
  await expect(workbench.locator('.markdown-body h1')).toHaveAttribute('contenteditable', 'true')
  await editor.press('Meta+Home')
  await page.keyboard.type('Saved fixture draft\n')
  await workbench.getByRole('button', { name: '保存修改' }).click()
  await expect.poll(() => readFileSync(filePath, 'utf8').includes('Saved fixture draft')).toBe(true)
  await expect(workbench.locator('.markdown-body')).toContainText('Saved fixture draft')
  await page.screenshot({ path: testInfo.outputPath('large-edit-compare.png') })
})
