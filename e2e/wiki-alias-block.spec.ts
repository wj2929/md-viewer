import { test, expect, openFolderViaIPC } from './fixtures/electron'
import { join } from 'node:path'
import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'

const padding = Array.from({ length: 100 }, (_, index) => `前置段落 ${index}\n\n`).join('')

test.describe('Wiki 别名与精确块定位', () => {
  test('别名反链排除嵌入，覆盖不完整时窄窗明确提示而非显示没有链接', async ({ page, electronApp, testDir }, testInfo) => {
    const target = join(testDir, 'actual.md'), source = join(testDir, 'source.md')
    writeFileSync(target, '---\naliases: Guide\n---\n\n# 目标')
    writeFileSync(source, '正文提及 [[Guide]]。\n\n[明确链接](./actual.md)\n\n![[Guide]]')
    await openFolderViaIPC(electronApp, testDir)
    await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), target)
    await expect(page.locator('.markdown-body h1')).toHaveText('目标')
    await page.locator('.floating-nav button[aria-label^="链接到这里"]').click()
    await expect(page.locator('.backlinks-summary')).toHaveText('1 个文档 · 2 处链接')
    writeFileSync(join(testDir, 'bad.md'), '---\naliases: [broken\n---')
    await expect(page.getByText('别名关系尚未全部确认，以下不是全量。', { exact: true })).toBeVisible()
    await expect(page.locator('.backlinks-summary')).toHaveText('1 个文档 · 1 处链接')
    await electronApp.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(800, 720))
    await page.getByRole('radio', { name: '暗色主题' }).click()
    await page.screenshot({ path: testInfo.outputPath('alias-backlinks-partial-dark-800.png') })
    writeFileSync(source, '正文提及 [[Guide]]。')
    await expect(page.getByText('暂未确认链接', { exact: true })).toBeVisible()
    await expect(page.getByText('还没有文档链接到这里', { exact: true })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath('alias-backlinks-unconfirmed-dark-800.png') })
  })
  for (const diskBlock of [false, true]) for (const draftBlock of [false, true]) {
    test(`跨页采用实际草稿：磁盘块 ${diskBlock}、草稿块 ${draftBlock}`, async ({ page, electronApp, testDir }) => {
      const source = join(testDir, 'Source.md'), target = join(testDir, 'Target.md')
      const disk = '# 草稿目标\n\n' + padding + '实际目标' + (diskBlock ? ' ^remote' : '') + '\n\n' + padding
      writeFileSync(source, '# 来源\n\n[[Target#^remote|指定块]]')
      writeFileSync(target, disk)
      page.on('dialog', dialog => void dialog.accept())
      await openFolderViaIPC(electronApp, testDir)
      await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), target)
      await expect(page.locator('.markdown-body h1')).toHaveText('草稿目标')
      await electronApp.evaluate(({ BrowserWindow }, filePath) => {
        BrowserWindow.getAllWindows()[0]?.webContents.send('markdown:quick-edit', { filePath, mode: 'document' })
      }, target)
      await expect(page.getByLabel('Target.md 编辑工作区')).toBeVisible()
      await page.locator('.markdown-workbench-preview-pane .markdown-preview-editable-block', { hasText: '实际目标' })
        .fill('草稿中的实际目标' + (draftBlock ? ' ^remote' : ''))
      await page.getByRole('button', { name: '退出编辑模式' }).click()
      await expect(page.getByText('草稿预览，未保存')).toBeVisible()
      await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), source)
      await expect(page.locator('.markdown-body h1')).toHaveText('来源')
      await page.getByRole('link', { name: '指定块', exact: true }).click()
      if (draftBlock) {
        await expect(page.locator('[id="md-block:remote"]')).toBeInViewport()
        await expect(page.getByText('草稿预览，未保存')).toBeVisible()
        await page.locator('[id="md-block:remote"]').hover()
        await page.mouse.wheel(0, -1200)
        await page.waitForTimeout(700)
        await expect(page.locator('[id="md-block:remote"]')).not.toBeInViewport()
      } else {
        await expect(page.getByText('未找到块 ^remote（当前草稿）。', { exact: true })).toBeVisible()
        await expect(page.locator('.markdown-body h1')).toHaveText('来源')
      }
      expect(readFileSync(target, 'utf8')).toBe(disk)
    })
  }

  test('同页块不读取已删除的磁盘文件，伪造保留 ID 不能定位', async ({ page, electronApp, testDir }) => {
    const source = join(testDir, 'source.md')
    writeFileSync(source, '# 来源\n\n[[#^local|同页块]]\n\n[[#^forged|伪造块]]\n\n<div id="md-block:forged">伪造</div>\n\n' + padding + '实际目标 ^local')
    await openFolderViaIPC(electronApp, testDir)
    await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), source)
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
    await page.getByRole('link', { name: '伪造块', exact: true }).click()
    await expect(page.getByText('链接跳转失败：未找到块 ^forged（当前显示内容）。', { exact: true })).toBeVisible()
    await expect(page.locator('[id="md-block:forged"]')).toHaveCount(0)
    unlinkSync(source)
    await page.getByRole('link', { name: '同页块', exact: true }).click()
    await expect(page.locator('[id="md-block:local"]')).toBeInViewport()
  })
  test('同页块与别名跨页块进入视口；缺失不激活；重复别名不猜测', async ({ page, electronApp, testDir }, testInfo) => {
    const source = join(testDir, 'source.md')
    writeFileSync(source, '# 来源\n\n[[#^local|同页块]]\n\n[普通块](#^local)\n\n[[Guide#^remote|别名块]]\n\n[[版本 1.0#^remote|点号别名块]]\n\n[[Guide#^absent|缺失块]]\n\n[[Duplicate|重复别名]]\n\n' + padding + '本地目标 ^local\n')
    writeFileSync(join(testDir, 'actual.md'), '---\naliases: [Guide, 版本 1.0, Duplicate]\n---\n\n# 目标\n\n' + padding + '远端目标 ^remote\n')
    writeFileSync(join(testDir, 'other.md'), '---\naliases: [Duplicate]\n---\n\n# 其他')
    await page.setViewportSize({ width: 1200, height: 800 })
    await openFolderViaIPC(electronApp, testDir)
    await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), source)
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
    await page.getByRole('link', { name: '同页块', exact: true }).click()
    await expect(page.locator('[id="md-block:local"]')).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath('same-page-block.png') })
    await page.getByRole('link', { name: '普通块', exact: true }).click()
    await expect(page.locator('[id="md-block:local"]')).toBeInViewport()
    await page.getByRole('link', { name: '缺失块', exact: true }).click()
    await expect(page.getByText('未找到块 ^absent。', { exact: true })).toBeVisible()
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
    await page.getByRole('link', { name: '重复别名', exact: true }).click()
    await expect(page.getByText('链接跳转失败：Wiki 名称对应多个文档，请使用明确文件路径。', { exact: true })).toBeVisible()
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
    await page.getByRole('link', { name: '别名块', exact: true }).click()
    await expect(page.locator('.markdown-body h1')).toHaveText('目标')
    await expect(page.locator('[id="md-block:remote"]')).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath('alias-remote-block.png') })
    await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), source)
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
    await page.getByRole('link', { name: '点号别名块', exact: true }).click()
    await expect(page.locator('[id="md-block:remote"]')).toBeInViewport()
  })

  test('索引外真实文件遮蔽别名，未知后缀的真实附件保持附件交互', async ({ page, electronApp, testDir }) => {
    mkdirSync(join(testDir, 'vendor'))
    const source = join(testDir, 'source.md')
    writeFileSync(source, '# 来源\n\n[[Guide|文件优先]]\n\n[[版本 1.0|真实附件]]')
    writeFileSync(join(testDir, 'actual.md'), '---\naliases: [Guide, 版本 1.0]\n---\n\n# 别名目标')
    writeFileSync(join(testDir, 'vendor', 'Guide.md'), '# 真实文件')
    writeFileSync(join(testDir, 'vendor', '版本 1.0'), 'plain attachment')
    await openFolderViaIPC(electronApp, testDir)
    await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), source)
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
    await page.getByRole('link', { name: '文件优先', exact: true }).click()
    await expect(page.locator('.markdown-body h1')).toHaveText('真实文件')
    await page.evaluate(file => window.api.testOpenMarkdownFile?.(file), source)
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
    await page.getByRole('link', { name: '真实附件', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.locator('.markdown-body h1')).toHaveText('来源')
  })
})
